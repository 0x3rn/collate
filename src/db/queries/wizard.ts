export class WizardError extends Error {
  public readonly code: "NOT_FOUND" | "VALIDATION_ERROR" | "FORBIDDEN";
  public readonly status: number;

  constructor(
    code: "NOT_FOUND" | "VALIDATION_ERROR" | "FORBIDDEN",
    message: string,
    status: number
  ) {
    super(message);
    this.name = "WizardError";
    this.code = code;
    this.status = status;
  }
}

export interface HydratedWizardState {
  project: ProjectRecord;
  settings: Omit<ProjectSettingsRecord, "frontMatterJson" | "coverJson"> & {
    frontMatter: FrontMatterToggles;
    cover: CoverDetails;
  };
  questions: QuestionRecord[];
  chapters: ChapterRecord[];
  feasibilityReports: Array<
    Omit<FeasibilityReportRecord, "reasonsJson" | "coverageJson"> & {
      reasons: string[];
      coverage: {
        sourcesFound: number;
        credibleRelevantSources?: number;
        accessibleSources?: number;
        distinctDomains?: number;
        subtopicsCovered: number;
        totalSubtopics?: number;
        idealPagesReason: string;
        requiresPrimaryData?: boolean;
        primaryDataNotice?: string | null;
        suggestedRefinements?: string[];
        subtopicBreakdown?: Array<{ subtopic: string; credibleSources: number; covered: boolean }>;
      };
    }
  >;
}

function safeParseFrontMatter(raw: string): FrontMatterToggles {
  try {
    return FrontMatterTogglesSchema.parse(JSON.parse(raw));
  } catch {
    return { ...DEFAULT_FRONT_MATTER };
  }
}

function safeParseCover(raw: string): CoverDetails {
  try {
    return CoverDetailsSchema.parse(JSON.parse(raw));
  } catch {
    return { ...DEFAULT_COVER_DETAILS };
  }
}

async function ensureDefaultSettings(
  db: AppDb,
  projectId: string,
  now: Date,
  options: { type?: ProjectType; useChapters?: boolean; isExperimental?: boolean } = {}
): Promise<ProjectSettingsRecord> {
  const existing = await db
    .select()
    .from(projectSettings)
    .where(eq(projectSettings.projectId, projectId))
    .limit(1);

  if (existing[0]) return existing[0];

  const resolvedType = options.type ?? "project";
  const useChapters =
    resolvedType === "assignment"
      ? false
      : (options.useChapters ?? defaultUseChaptersForType(resolvedType));
  const isExperimental = resolvedType === "assignment" ? false : Boolean(options.isExperimental);
  const frontMatterDefaults = defaultFrontMatterForStructure(resolvedType, useChapters);

  const [created] = await db
    .insert(projectSettings)
    .values({
      projectId,
      citationStyle: "apa7",
      inlineMode: "inline_and_list",
      font: "Times New Roman",
      fontSizePt: 12,
      lineSpacing: "double",
      marginsMm: 25,
      pageSize: "a4",
      pageNumbering: true,
      headingColor: "black",
      spelling: "uk",
      isExperimental,
      experimentalDataMode: "user_provided",
      useChapters,
      frontMatterJson: JSON.stringify(frontMatterDefaults),
      coverJson: JSON.stringify(DEFAULT_COVER_DETAILS),
      updatedAt: now,
    })
    .returning();

  if (!created) {
    throw new Error("Failed to initialize default project settings");
  }
  return created;
}

async function seedDefaultChaptersForProject(params: {
  db: AppDb;
  projectId: string;
  type: ProjectType;
  isExperimental: boolean;
  useChapters: boolean;
  level?: string | null;
  targetPages?: number | null;
  lineSpacing: ProjectSettingsRecord["lineSpacing"];
  now: Date;
}): Promise<void> {
  const { db, projectId, type, isExperimental, useChapters, level, lineSpacing, now } = params;
  if (type === "assignment") return;

  const defaults = getDefaultChaptersForType(type, { isExperimental, useChapters, level });
  const { idealPages } = recommendMockIdealPages({ type, level });
  const budgetPages = params.targetPages ?? idealPages;
  const budgeted = allocateChapterBudgets(defaults, budgetPages, lineSpacing, { isExperimental });
  const defaultsByNum = new Map(defaults.map((d) => [d.number, d]));

  await db.delete(chapters).where(eq(chapters.projectId, projectId));
  for (const ch of budgeted) {
    const def = defaultsByNum.get(ch.number);
    const chapterId = `chp_${crypto.randomUUID()}`;
    await db.insert(chapters).values({
      id: chapterId,
      projectId,
      number: ch.number,
      title: ch.title,
      chapterType: ch.chapterType,
      brief: def?.brief ?? null,
      pageBudget: ch.pageBudget,
      wordBudget: ch.wordBudget,
      isAutoReferences: false,
      status: "not_started",
      createdAt: now,
      updatedAt: now,
    });
  }

  await db.insert(chapters).values({
    id: `chp_${crypto.randomUUID()}`,
    projectId,
    number: budgeted.length + 1,
    title: "References",
    chapterType: "references",
    pageBudget: null,
    wordBudget: null,
    isAutoReferences: true,
    status: "not_started",
    createdAt: now,
    updatedAt: now,
  });
}

export async function createWizardDraftProject(
  db: AppDb,
  userId: string,
  type: ProjectType,
  now: Date = new Date(),
  initialTitle?: string,
  options: { useChapters?: boolean; isExperimental?: boolean } = {}
): Promise<HydratedWizardState> {
  if (!userId.trim()) {
    throw new WizardError("VALIDATION_ERROR", "Authenticated userId is required.", 400);
  }

  const projectId = `prj_${crypto.randomUUID()}`;
  const cleanedTitle = initialTitle?.trim().slice(0, 300) ?? "";
  const defaultTitle =
    cleanedTitle.length > 0
      ? cleanedTitle
      : type === "assignment"
        ? "Untitled assignment"
        : `Untitled ${type}`;

  const useChapters =
    type === "assignment" ? false : (options.useChapters ?? defaultUseChaptersForType(type));
  const isExperimental = type === "assignment" ? false : Boolean(options.isExperimental);

  await db.insert(projects).values({
    id: projectId,
    userId,
    type,
    title: defaultTitle,
    status: "draft",
    wizardStep: 2,
    createdAt: now,
    updatedAt: now,
  });

  await ensureDefaultSettings(db, projectId, now, { type, useChapters, isExperimental });

  if (type !== "assignment") {
    await seedDefaultChaptersForProject({
      db,
      projectId,
      type,
      isExperimental,
      useChapters,
      lineSpacing: "double",
      now,
    });
  }

  const hydrated = await getWizardStateForUser(db, userId, projectId);
  if (!hydrated) {
    throw new Error("Failed to load newly created draft project");
  }
  return hydrated;
}

export async function getWizardStateForUser(
  db: AppDb,
  userId: string,
  projectId: string
): Promise<HydratedWizardState | null> {
  if (!userId.trim() || !projectId.trim()) return null;

  const [project] = await db
    .select()
    .from(projects)
    .where(and(eq(projects.id, projectId), eq(projects.userId, userId)))
    .limit(1);

  if (!project) return null;

  const settingsRow = await ensureDefaultSettings(db, project.id, new Date());

  const questionRows = await db
    .select()
    .from(questions)
    .where(eq(questions.projectId, project.id))
    .orderBy(asc(questions.orderIndex));

  const chapterRows = await db
    .select()
    .from(chapters)
    .where(eq(chapters.projectId, project.id))
    .orderBy(asc(chapters.number));

  const reportRows = await db
    .select()
    .from(feasibilityReports)
    .where(eq(feasibilityReports.projectId, project.id));

  return {
    project,
    settings: {
      projectId: settingsRow.projectId,
      citationStyle: settingsRow.citationStyle,
      inlineMode: settingsRow.inlineMode,
      font: settingsRow.font,
      fontSizePt: settingsRow.fontSizePt,
      lineSpacing: settingsRow.lineSpacing,
      marginsMm: settingsRow.marginsMm,
      pageSize: settingsRow.pageSize,
      pageNumbering: settingsRow.pageNumbering,
      headingColor: settingsRow.headingColor,
      spelling: settingsRow.spelling,
      isExperimental: settingsRow.isExperimental,
      experimentalDataMode: settingsRow.experimentalDataMode,
      useChapters: settingsRow.useChapters,
      updatedAt: settingsRow.updatedAt,
      frontMatter: safeParseFrontMatter(settingsRow.frontMatterJson),
      cover: safeParseCover(settingsRow.coverJson),
    },
    questions: questionRows,
    chapters: chapterRows,
    feasibilityReports: reportRows.map((row) => {
      let reasons: string[];
      let coverage = { sourcesFound: 0, subtopicsCovered: 0, idealPagesReason: "" };
      try {
        reasons = JSON.parse(row.reasonsJson) as string[];
      } catch {
        reasons = [];
      }
      try {
        coverage = JSON.parse(row.coverageJson) as typeof coverage;
      } catch {
        // Keep defaults
      }
      return {
        id: row.id,
        projectId: row.projectId,
        questionId: row.questionId,
        verdict: row.verdict,
        score: row.score,
        isMocked: row.isMocked,
        createdAt: row.createdAt,
        reasons,
        coverage,
      };
    }),
  };
}

export async function saveWizardStepForUser(
  db: AppDb,
  userId: string,
  projectId: string,
  rawPayload: unknown,
  now: Date = new Date(),
  options: { allowMockVerdict?: boolean } = {}
): Promise<HydratedWizardState> {
  const existing = await getWizardStateForUser(db, userId, projectId);
  if (!existing) {
    throw new WizardError("NOT_FOUND", "Project not found.", 404);
  }

  const parsed = WizardStepPayloadSchema.safeParse(rawPayload);
  if (!parsed.success) {
    throw new WizardError(
      "VALIDATION_ERROR",
      parsed.error.issues[0]?.message ?? "Check your selections and try again.",
      400
    );
  }

  const payload = parsed.data;

  if (payload.step === 1) {
    const nextUseChapters =
      payload.type === "assignment"
        ? false
        : (payload.useChapters ?? defaultUseChaptersForType(payload.type));

    await db
      .update(projects)
      .set({
        type: payload.type,
        wizardStep: Math.max(existing.project.wizardStep, 2),
        updatedAt: now,
      })
      .where(and(eq(projects.id, projectId), eq(projects.userId, userId)));

    await db
      .update(projectSettings)
      .set({
        useChapters: nextUseChapters,
        frontMatterJson: JSON.stringify(
          defaultFrontMatterForStructure(payload.type, nextUseChapters)
        ),
        updatedAt: now,
      })
      .where(eq(projectSettings.projectId, projectId));

    if (payload.type === "assignment") {
      await db.delete(chapters).where(eq(chapters.projectId, projectId));
    } else if (existing.chapters.length === 0) {
      await seedDefaultChaptersForProject({
        db,
        projectId,
        type: payload.type,
        isExperimental: existing.settings.isExperimental,
        useChapters: nextUseChapters,
        level: existing.project.level,
        targetPages: existing.project.targetPages,
        lineSpacing: existing.settings.lineSpacing,
        now,
      });
    }
  } else if (payload.step === 2) {
    if (existing.project.type === "assignment") {
      const list = payload.questions ?? [];
      if (list.length === 0) {
        throw new WizardError(
          "VALIDATION_ERROR",
          "Add at least one assignment question before continuing.",
          400
        );
      }

      await db.delete(questions).where(eq(questions.projectId, projectId));
      for (let i = 0; i < list.length; i++) {
        await db.insert(questions).values({
          id: `qst_${crypto.randomUUID()}`,
          projectId,
          text: list[i]!,
          orderIndex: i + 1,
          createdAt: now,
        });
      }
    }

    await db
      .update(projects)
      .set({
        title: payload.title,
        field: payload.field || null,
        level: payload.level || null,
        institution: payload.institution || null,
        supervisorNotes: payload.supervisorNotes || null,
        wizardStep: Math.max(existing.project.wizardStep, 3),
        updatedAt: now,
      })
      .where(and(eq(projects.id, projectId), eq(projects.userId, userId)));

    if (existing.project.type !== "assignment") {
      const nextIsExperimental = Boolean(payload.isExperimental);
      const nextDataMode = nextIsExperimental ? payload.experimentalDataMode : "user_provided";
      const nextUseChapters =
        payload.useChapters !== undefined ? payload.useChapters : existing.settings.useChapters;
      const structureChanged =
        nextIsExperimental !== existing.settings.isExperimental ||
        nextUseChapters !== existing.settings.useChapters;

      let nextFrontMatterJson: string | undefined;
      if (nextUseChapters !== existing.settings.useChapters) {
        const prevDefaultFm = defaultFrontMatterForStructure(
          existing.project.type,
          existing.settings.useChapters
        );
        if (JSON.stringify(existing.settings.frontMatter) === JSON.stringify(prevDefaultFm)) {
          nextFrontMatterJson = JSON.stringify(
            defaultFrontMatterForStructure(existing.project.type, nextUseChapters)
          );
        }
      }

      await db
        .update(projectSettings)
        .set({
          isExperimental: nextIsExperimental,
          experimentalDataMode: nextDataMode,
          useChapters: nextUseChapters,
          ...(nextFrontMatterJson ? { frontMatterJson: nextFrontMatterJson } : {}),
          updatedAt: now,
        })
        .where(eq(projectSettings.projectId, projectId));

      if (structureChanged) {
        const nonRefChapters = existing.chapters.filter((ch) => !ch.isAutoReferences);
        const hasStartedAny = nonRefChapters.some((ch) => ch.status !== "not_started");
        const stillUsingDefaultTitles = isAutoGeneratedDefaultChapters(
          nonRefChapters.map((c) => c.title)
        );
        if (!hasStartedAny && (stillUsingDefaultTitles || existing.project.wizardStep <= 4)) {
          await seedDefaultChaptersForProject({
            db,
            projectId,
            type: existing.project.type,
            isExperimental: nextIsExperimental,
            useChapters: nextUseChapters,
            level: payload.level || existing.project.level,
            targetPages: existing.project.targetPages,
            lineSpacing: existing.settings.lineSpacing,
            now,
          });
          await db
            .update(projectMemory)
            .set({ outlineJson: "{}", updatedAt: now })
            .where(
              and(eq(projectMemory.projectId, projectId), eq(projectMemory.outlineLocked, false))
            );
        }
      }
    }
  } else if (payload.step === 3) {
    if (!options.allowMockVerdict) {
      throw new WizardError(
        "FORBIDDEN",
        "Simulated feasibility verdicts are disabled outside local development. Run a live source sweep instead.",
        403
      );
    }

    // Local development-only mock research sweep helper (never enabled in staging/prod; NN-1)
    const { idealPages, reason } = recommendMockIdealPages({
      type: existing.project.type,
      level: existing.project.level,
      questionCount: existing.questions.length,
    });

    await db.delete(feasibilityReports).where(eq(feasibilityReports.projectId, projectId));

    const verdict = payload.simulateVerdict;
    const score = verdict === "feasible" ? 84 : verdict === "needs_refinement" ? 56 : 22;
    const mockReasons =
      verdict === "feasible"
        ? [
            "Mock check: sufficient research and web coverage simulated for Phase 2 wizard testing.",
            "Real multi-source verification and DOI checks will replace this screen in Phases 3 and 4.",
          ]
        : verdict === "needs_refinement"
          ? [
              "Mock check: topic scope appears broad; narrowing the region or timeframe is recommended.",
            ]
          : [
              "Mock check: insufficient verifiable sources found to draft this topic without guessing.",
            ];

    if (existing.project.type === "assignment" && existing.questions.length > 0) {
      for (const q of existing.questions) {
        await db.insert(feasibilityReports).values({
          id: `fsr_${crypto.randomUUID()}`,
          projectId,
          questionId: q.id,
          verdict,
          score,
          reasonsJson: JSON.stringify(mockReasons),
          coverageJson: JSON.stringify({
            sourcesFound: verdict === "not_feasible" ? 2 : 14,
            subtopicsCovered: verdict === "not_feasible" ? 1 : 3,
            idealPagesReason: reason,
          }),
          isMocked: true,
          createdAt: now,
        });
      }
    } else {
      await db.insert(feasibilityReports).values({
        id: `fsr_${crypto.randomUUID()}`,
        projectId,
        questionId: null,
        verdict,
        score,
        reasonsJson: JSON.stringify(mockReasons),
        coverageJson: JSON.stringify({
          sourcesFound: verdict === "not_feasible" ? 3 : 38,
          subtopicsCovered: verdict === "not_feasible" ? 1 : 6,
          idealPagesReason: reason,
        }),
        isMocked: true,
        createdAt: now,
      });
    }

    await db
      .update(projects)
      .set({
        status: verdict,
        idealPages,
        targetPages: existing.project.targetPages ?? idealPages,
        wizardStep: verdict === "feasible" ? Math.max(existing.project.wizardStep, 4) : 3,
        updatedAt: now,
      })
      .where(and(eq(projects.id, projectId), eq(projects.userId, userId)));
  } else if (payload.step === 4) {
    const nextStep = existing.project.type === "assignment" ? 6 : 5;
    await db
      .update(projects)
      .set({
        targetPages: payload.targetPages,
        wizardStep: Math.max(existing.project.wizardStep, nextStep),
        updatedAt: now,
      })
      .where(and(eq(projects.id, projectId), eq(projects.userId, userId)));

    // Recompute chapter page budgets if chapters already exist
    const nonRefChapters = existing.chapters.filter((ch) => !ch.isAutoReferences);
    if (nonRefChapters.length > 0) {
      const rebudgeted = allocateChapterBudgets(
        nonRefChapters.map((c) => ({
          number: c.number,
          title: c.title,
          chapterType: c.chapterType,
        })),
        payload.targetPages,
        existing.settings.lineSpacing,
        { isExperimental: existing.settings.isExperimental }
      );
      for (const item of rebudgeted) {
        await db
          .update(chapters)
          .set({
            pageBudget: item.pageBudget,
            wordBudget: item.wordBudget,
            updatedAt: now,
          })
          .where(and(eq(chapters.projectId, projectId), eq(chapters.number, item.number)));
      }
    }
  } else if (payload.step === 5) {
    if (existing.project.type === "assignment") {
      throw new WizardError(
        "VALIDATION_ERROR",
        "Assignments use question lists rather than chapters.",
        400
      );
    }

    // Preserve tailored chapter metadata & sections for unchanged titles (e.g., from AI topic suggestion)
    const existingChapterIds = existing.chapters.map((c) => c.id);
    const existingSectionsByChapterId = new Map<string, string[]>();
    if (existingChapterIds.length > 0) {
      const secRows = await db
        .select({
          chapterId: sections.chapterId,
          orderIndex: sections.orderIndex,
          heading: sections.heading,
        })
        .from(sections)
        .where(inArray(sections.chapterId, existingChapterIds))
        .orderBy(asc(sections.orderIndex));
      for (const row of secRows) {
        const list = existingSectionsByChapterId.get(row.chapterId) ?? [];
        list.push(row.heading);
        existingSectionsByChapterId.set(row.chapterId, list);
      }
    }
    const existingMetaByTitle = new Map(
      existing.chapters
        .filter((c) => !c.isAutoReferences)
        .map((c) => [
          c.title.trim().toLowerCase(),
          {
            chapterType: c.chapterType,
            brief: c.brief,
            sectionHeadings: existingSectionsByChapterId.get(c.id) ?? [],
          },
        ])
    );

    const sorted = [...payload.chapters].sort((a, b) => a.number - b.number);
    const targetPages = existing.project.targetPages ?? existing.project.idealPages ?? 50;
    const budgeted = allocateChapterBudgets(
      sorted.map((ch) => {
        const preserved = existingMetaByTitle.get(ch.title.trim().toLowerCase());
        return {
          number: ch.number,
          title: ch.title,
          chapterType: preserved?.chapterType,
        };
      }),
      targetPages,
      existing.settings.lineSpacing,
      { isExperimental: existing.settings.isExperimental }
    );
    const maxChapterNum = budgeted.reduce((max, item) => Math.max(max, item.number), 0);

    await db.delete(chapters).where(eq(chapters.projectId, projectId));
    for (const ch of budgeted) {
      const preserved = existingMetaByTitle.get(ch.title.trim().toLowerCase());
      const chapterId = `chp_${crypto.randomUUID()}`;
      await db.insert(chapters).values({
        id: chapterId,
        projectId,
        number: ch.number,
        title: ch.title,
        chapterType: ch.chapterType,
        brief: preserved?.brief ?? null,
        pageBudget: ch.pageBudget,
        wordBudget: ch.wordBudget,
        isAutoReferences: false,
        status: "not_started",
        createdAt: now,
        updatedAt: now,
      });

      if (preserved && preserved.sectionHeadings.length > 0) {
        const plannedSecs = distributeWordsAcrossSections(preserved.sectionHeadings, ch.wordBudget);
        for (const sec of plannedSecs) {
          await db.insert(sections).values({
            id: `sec_${crypto.randomUUID()}`,
            chapterId,
            orderIndex: sec.orderIndex,
            heading: sec.heading,
            wordBudget: sec.wordBudget,
            status: "not_started",
            createdAt: now,
            updatedAt: now,
          });
        }
      }
    }

    // Automatically append References chapter assembled by the citation engine (Section 5 & 7)
    await db.insert(chapters).values({
      id: `chp_${crypto.randomUUID()}`,
      projectId,
      number: maxChapterNum + 1,
      title: "References",
      chapterType: "references",
      pageBudget: null,
      wordBudget: null,
      isAutoReferences: true,
      status: "not_started",
      createdAt: now,
      updatedAt: now,
    });

    await db
      .update(projectMemory)
      .set({ outlineJson: "{}", updatedAt: now })
      .where(and(eq(projectMemory.projectId, projectId), eq(projectMemory.outlineLocked, false)));

    await db
      .update(projectSettings)
      .set({
        frontMatterJson: JSON.stringify(payload.frontMatter),
        updatedAt: now,
      })
      .where(eq(projectSettings.projectId, projectId));

    await db
      .update(projects)
      .set({
        wizardStep: Math.max(existing.project.wizardStep, 6),
        updatedAt: now,
      })
      .where(and(eq(projects.id, projectId), eq(projects.userId, userId)));
  } else if (payload.step === 6) {
    await db
      .update(projectSettings)
      .set({
        citationStyle: payload.citationStyle,
        inlineMode: payload.inlineMode,
        updatedAt: now,
      })
      .where(eq(projectSettings.projectId, projectId));

    await db
      .update(projects)
      .set({
        wizardStep: Math.max(existing.project.wizardStep, 7),
        updatedAt: now,
      })
      .where(and(eq(projects.id, projectId), eq(projects.userId, userId)));
  } else if (payload.step === 7) {
    await db
      .update(projectSettings)
      .set({
        font: payload.font,
        fontSizePt: payload.fontSizePt,
        lineSpacing: payload.lineSpacing,
        marginsMm: payload.marginsMm,
        pageSize: payload.pageSize,
        pageNumbering: payload.pageNumbering,
        headingColor: payload.headingColor,
        spelling: payload.spelling,
        coverJson: JSON.stringify(payload.cover),
        updatedAt: now,
      })
      .where(eq(projectSettings.projectId, projectId));

    await db
      .update(projects)
      .set({
        wizardStep: 8,
        updatedAt: now,
      })
      .where(and(eq(projects.id, projectId), eq(projects.userId, userId)));
  } else if (payload.step === 8) {
    await db
      .update(projects)
      .set({
        status: "outline_pending",
        wizardStep: 8,
        updatedAt: now,
      })
      .where(and(eq(projects.id, projectId), eq(projects.userId, userId)));
  }

  const refreshed = await getWizardStateForUser(db, userId, projectId);
  if (!refreshed) {
    throw new Error("Failed to reload wizard state after save");
  }
  return refreshed;
}

export async function updateProjectPageSizeForUser(
  db: AppDb,
  userId: string,
  projectId: string,
  pageSize: PageSize,
  now: Date = new Date()
): Promise<{ pageSize: PageSize }> {
  const existing = await getWizardStateForUser(db, userId, projectId);
  if (!existing) {
    throw new WizardError("NOT_FOUND", "Project not found.", 404);
  }

  await db
    .update(projectSettings)
    .set({ pageSize, updatedAt: now })
    .where(eq(projectSettings.projectId, projectId));

  await db
    .update(projects)
    .set({ updatedAt: now })
    .where(and(eq(projects.id, projectId), eq(projects.userId, userId)));

  return { pageSize };
}
