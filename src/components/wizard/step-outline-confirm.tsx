"use client";

import { Button } from "@/components/ui/button";
import { formatProjectType } from "@/lib/ui/formatters";
import type { SerializedWizardState } from "@/lib/wizard/http-handlers";

export function StepOutlineConfirm({
  wizard,
  saving,
  onConfirm,
  onBack,
}: {
  wizard: SerializedWizardState;
  saving: boolean;
  onConfirm: () => Promise<void>;
  onBack: () => void;
}) {
  const { project, settings, chapters, questions } = wizard;
  const enabledFrontMatter = Object.entries(settings.frontMatter)
    .filter(([, enabled]) => enabled)
    .map(([key]) => key.replace(/([A-Z])/g, " $1").toLowerCase());

  return (
    <div className="space-y-6">
      <div className="space-y-1">
        <h2 className="text-2xl font-medium">Review and confirm your outline</h2>
        <p className="text-sm text-[var(--neutral-600)]">
          Check your topic, page count, chapters, citations, and layout before saving your project
          plan.
        </p>
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
        <div className="p-4 rounded-[var(--radius-sm)] border border-[var(--neutral-200)] bg-[var(--neutral-50)] space-y-1">
          <p className="text-xs font-medium text-[var(--neutral-600)] m-0">
            Work type &amp; length
          </p>
          <p className="text-base font-semibold text-[var(--neutral-900)] m-0 tabular-nums">
            {formatProjectType(project.type)} · {project.targetPages ?? project.idealPages ?? "—"}{" "}
            pages
          </p>
          <p className="text-sm text-[var(--neutral-700)] m-0">{project.title}</p>
        </div>

        <div className="p-4 rounded-[var(--radius-sm)] border border-[var(--neutral-200)] bg-[var(--neutral-50)] space-y-1">
          <p className="text-xs font-medium text-[var(--neutral-600)] m-0">
            Citations &amp; layout
          </p>
          <p className="text-base font-semibold text-[var(--neutral-900)] m-0">
            {settings.citationStyle.toUpperCase()} (
            {settings.inlineMode === "inline_and_list" ? "inline + list" : "list only"})
          </p>
          <p className="text-sm text-[var(--neutral-700)] m-0">
            {settings.font}, {settings.fontSizePt}pt, {settings.lineSpacing.replace("_", " ")}{" "}
            spacing, {settings.spelling.toUpperCase()} English
          </p>
        </div>
      </div>

      {project.type === "assignment" ? (
        <div className="bg-white border border-[var(--neutral-200)] rounded-[var(--radius-md)] p-5 space-y-3">
          <h3 className="text-lg font-medium m-0">Assignment questions ({questions.length})</h3>
          <ol className="list-decimal pl-5 space-y-2 text-sm text-[var(--neutral-800)] m-0">
            {questions.map((q) => (
              <li key={q.id}>{q.text}</li>
            ))}
          </ol>
        </div>
      ) : (
        <div className="bg-white border border-[var(--neutral-200)] rounded-[var(--radius-md)] p-5 space-y-4">
          <h3 className="text-lg font-medium m-0">Chapter plan ({chapters.length} sections)</h3>
          <ul className="divide-y divide-[var(--neutral-200)] list-none p-0 m-0">
            {chapters.map((ch) => (
              <li
                key={ch.id}
                className="py-3 flex flex-col sm:flex-row sm:items-center justify-between gap-1"
              >
                <div>
                  <span className="text-xs font-semibold text-[var(--neutral-500)] mr-2 tabular-nums">
                    {ch.isAutoReferences ? "AUTO" : `Ch. ${ch.number}`}
                  </span>
                  <span className="text-sm font-medium text-[var(--neutral-900)]">{ch.title}</span>
                </div>
                <span className="text-xs text-[var(--neutral-600)] tabular-nums">
                  {ch.isAutoReferences
                    ? "Generated by citation engine"
                    : `~${ch.pageBudget ?? 0} pages (~${(ch.wordBudget ?? 0).toLocaleString()} words)`}
                </span>
              </li>
            ))}
          </ul>

          {enabledFrontMatter.length > 0 ? (
            <p className="text-xs text-[var(--neutral-600)] border-t border-[var(--neutral-200)] pt-3 m-0">
              Included front/back matter: {enabledFrontMatter.join(", ")}.
            </p>
          ) : null}
        </div>
      )}

      <div className="flex flex-wrap items-center justify-between gap-3 pt-2">
        <Button type="button" variant="secondary" onClick={onBack}>
          Back to formatting
        </Button>
        <Button
          type="button"
          loading={saving}
          loadingLabel="Confirming outline..."
          onClick={onConfirm}
        >
          Confirm outline and save project
        </Button>
      </div>
    </div>
  );
}
