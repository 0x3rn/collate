export function getPublicPricingSummary() {
  return {
    freeSweeps: BILLING_POLICY.freeFeasibilitySweepsPerUser,
    creditsPerPage: BILLING_POLICY.creditsPerPage,
    packs: CREDIT_PACKS.map((pack) => ({
      id: pack.id,
      label: pack.label,
      credits: pack.credits,
      ngnFormatted: `NGN ${(pack.amountNgnKobo / 100).toLocaleString("en-NG")}`,
      usdFormatted: `$${(pack.amountUsdCents / 100).toFixed(0)} USD`,
      description: pack.description,
    })),
  };
}
